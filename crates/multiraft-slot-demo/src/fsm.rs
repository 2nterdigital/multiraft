#[derive(Clone, Debug, Deserialize, Serialize, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
pub struct Command {
    pub key: String,
    pub command_id: String,
    pub delta: i64,
}
#[derive(Clone, Debug, Deserialize, Serialize, PartialEq, Eq)]
pub struct Effect {
    pub key: String,
    pub command_id: String,
    pub value: i64,
    pub accepted: bool,
}
#[derive(Clone, Default, Deserialize, Serialize)]
pub struct Image {
    pub group: u64,
    pub values: BTreeMap<String, i64>,
    pub commands: BTreeMap<String, (Command, Effect)>,
    pub apply_calls: u64,
}
#[derive(Default)]
pub struct GateState {
    pub command_id: Option<String>,
    pub entered: bool,
    pub released: bool,
}
#[derive(Default)]
pub struct Gate {
    pub state: Mutex<GateState>,
    pub changed: Condvar,
}
impl Gate {
    fn wait(&self, id: &str) -> io::Result<()> {
        let mut state = self
            .state
            .lock()
            .map_err(|_| io::Error::other("gate lock poisoned"))?;
        if state.command_id.as_deref() != Some(id) {
            return Ok(());
        }
        state.entered = true;
        self.changed.notify_all();
        let (mut state, timeout) = self
            .changed
            .wait_timeout_while(state, Duration::from_secs(45), |s| !s.released)
            .map_err(|_| io::Error::other("gate wait poisoned"))?;
        state.command_id = None;
        if timeout.timed_out() && !state.released {
            return Err(io::Error::other("test apply gate safety timeout"));
        }
        Ok(())
    }
}
/// Disk-backed variant: values, commands and the apply count live only in
/// RocksDB, committed with the applied position (`--fsm-storage disk`).
pub struct DiskImage {
    db: DiskFsmDb,
    /// Applied index found in RocksDB when this process opened the store.
    opened_index: Option<u64>,
}
const VALUES: &str = "values";
const COMMANDS: &str = "commands";
const BLOBS: &str = "blobs";
/// Test-only bulk command (`/bulk`): `BLOB_PREFIX`, a big-endian u64 seed and
/// u32 length. Apply generates that many incompressible bytes from the seed,
/// stores them under the log index, counts them and folds them into a SHA-256
/// chain so replicas can compare content cheaply. The Raft log stays small; the
/// FSM grows by the generated bytes.
pub const BLOB_PREFIX: &[u8] = b"BLOB";
pub const MAX_BLOB_BYTES: u32 = 4 * 1024 * 1024;
pub fn blob_command(seed: u64, len: u32) -> Vec<u8> {
    let mut command = BLOB_PREFIX.to_vec();
    command.extend(seed.to_be_bytes());
    command.extend(len.to_be_bytes());
    command
}
fn generate_blob(spec: &[u8]) -> io::Result<Vec<u8>> {
    let (seed, len) = match spec {
        [seed @ .., a, b, c, d] if seed.len() == 8 => (
            u64::from_be_bytes(seed.try_into().expect("8 bytes")),
            u32::from_be_bytes([*a, *b, *c, *d]),
        ),
        _ => return Err(io::Error::other("invalid blob command")),
    };
    if len > MAX_BLOB_BYTES {
        return Err(io::Error::other("blob too large"));
    }
    let mut state = seed.wrapping_mul(0x9E37_79B9_7F4A_7C15) | 1;
    let mut blob = Vec::with_capacity(len as usize);
    while blob.len() < len as usize {
        state ^= state << 13;
        state ^= state >> 7;
        state ^= state << 17;
        blob.extend_from_slice(&state.to_le_bytes());
    }
    blob.truncate(len as usize);
    Ok(blob)
}
impl DiskImage {
    pub fn open(path: &std::path::Path, group: u64) -> io::Result<Self> {
        let mut options = DiskFsmOptions::new(b"slot-demo-disk-v2".to_vec());
        options.column_families = vec![VALUES.into(), COMMANDS.into(), BLOBS.into()];
        // Bounded memtables keep the process small while GB-scale data is written.
        options.db_options.set_write_buffer_size(8 * 1024 * 1024);
        options.db_options.set_max_write_buffer_number(2);
        options
            .db_options
            .set_target_file_size_base(32 * 1024 * 1024);
        let db = DiskFsmDb::open(path, group, options)?;
        let opened_index = Self::read_u64(&db, b"applied_index")?;
        Ok(Self { db, opened_index })
    }
    fn read_u64(db: &DiskFsmDb, key: &[u8]) -> io::Result<Option<u64>> {
        let bytes = db
            .db()
            .get_cf(db.cf("default")?, key)
            .map_err(io::Error::other)?;
        bytes
            .map(|b| {
                Ok(u64::from_be_bytes(
                    b.try_into().map_err(|_| io::Error::other("bad u64 row"))?,
                ))
            })
            .transpose()
    }
    fn value(&self, key: &str) -> io::Result<i64> {
        let bytes = self
            .db
            .db()
            .get_cf(self.db.cf(VALUES)?, key)
            .map_err(io::Error::other)?;
        Ok(bytes
            .map(|b| serde_json::from_slice(&b))
            .transpose()?
            .unwrap_or(0))
    }
    fn command(&self, id: &str) -> io::Result<Option<(Command, Effect)>> {
        let bytes = self
            .db
            .db()
            .get_cf(self.db.cf(COMMANDS)?, id)
            .map_err(io::Error::other)?;
        Ok(bytes.map(|b| serde_json::from_slice(&b)).transpose()?)
    }
    fn blob_facts(&self) -> io::Result<serde_json::Value> {
        let chain = self
            .db
            .db()
            .get_cf(self.db.cf("default")?, b"blob_chain")
            .map_err(io::Error::other)?
            .map(|bytes| hex(&bytes));
        // Content of the newest blob rows, read back from the store itself.
        let mut tail = Vec::new();
        for row in self
            .db
            .db()
            .iterator_cf(self.db.cf(BLOBS)?, IteratorMode::End)
            .take(3)
        {
            let (key, value) = row.map_err(io::Error::other)?;
            tail.push(serde_json::json!([hex(&key), hex(&Sha256::digest(&value))]));
        }
        Ok(serde_json::json!({
            "count": Self::read_u64(&self.db, b"blob_count")?.unwrap_or(0),
            "bytes": Self::read_u64(&self.db, b"blob_bytes")?.unwrap_or(0),
            "chain": chain,
            "tail": tail,
        }))
    }
    fn commands(&self) -> io::Result<BTreeMap<String, (Command, Effect)>> {
        let mut out = BTreeMap::new();
        for row in self
            .db
            .db()
            .iterator_cf(self.db.cf(COMMANDS)?, IteratorMode::Start)
        {
            let (key, value) = row.map_err(io::Error::other)?;
            out.insert(
                String::from_utf8_lossy(&key).into_owned(),
                serde_json::from_slice(&value)?,
            );
        }
        Ok(out)
    }
}
fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}
pub struct DemoFsm {
    pub image: Image,
    pub layout: ClusterLayout,
    pub gate: Arc<Gate>,
    pub disk: Option<DiskImage>,
}
/// Same-id same-intent replays the stored effect; a changed intent is refused.
fn decide(
    existing: Option<&(Command, Effect)>,
    current: i64,
    command: &Command,
) -> io::Result<(Effect, bool)> {
    if let Some((original, effect)) = existing {
        return Ok(if original == command {
            (effect.clone(), false)
        } else {
            (
                Effect {
                    accepted: false,
                    ..effect.clone()
                },
                false,
            )
        });
    }
    let value = current
        .checked_add(command.delta)
        .ok_or_else(|| io::Error::other("counter overflow"))?;
    Ok((
        Effect {
            key: command.key.clone(),
            command_id: command.command_id.clone(),
            value,
            accepted: true,
        },
        true,
    ))
}
impl DemoFsm {
    fn check_key(&self, group: u64, key: &str) -> io::Result<()> {
        if group != self.image.group
            || self
                .layout
                .group_for_slot(
                    self.layout
                        .slot_for_key(key.as_bytes())
                        .map_err(io::Error::other)?,
                )
                .map_err(io::Error::other)?
                != group
        {
            return Err(io::Error::other("business key/group mismatch"));
        }
        Ok(())
    }
}
impl StateMachine for DemoFsm {
    type Error = io::Error;
    fn apply(&mut self, group: u64, _index: u64, data: &[u8]) -> io::Result<ApplyOut> {
        let command: Command = serde_json::from_slice(data)?;
        self.check_key(group, &command.key)?;
        self.gate.wait(&command.command_id)?;
        self.image.apply_calls += 1;
        let current = self.image.values.get(&command.key).copied().unwrap_or(0);
        let (effect, new) = decide(
            self.image.commands.get(&command.command_id),
            current,
            &command,
        )?;
        if new {
            self.image.values.insert(command.key.clone(), effect.value);
            self.image
                .commands
                .insert(command.command_id.clone(), (command, effect.clone()));
        }
        Ok(ApplyOut {
            effects: serde_json::to_vec(&effect)?,
        })
    }
    fn snapshot(&self, group: u64) -> io::Result<Vec<u8>> {
        if group != self.image.group {
            return Err(io::Error::other("snapshot group mismatch"));
        }
        Ok(serde_json::to_vec(&self.image)?)
    }
    fn restore(&mut self, group: u64, bytes: &[u8]) -> io::Result<()> {
        let image: Image = serde_json::from_slice(bytes)?;
        if image.group != group || group != self.image.group {
            return Err(io::Error::other("restore group mismatch"));
        }
        for key in image.values.keys() {
            self.check_key(group, key)?;
        }
        for (id, (command, effect)) in &image.commands {
            self.check_key(group, &command.key)?;
            if id != &command.command_id
                || effect.command_id != *id
                || effect.key != command.key
                || !effect.accepted
            {
                return Err(io::Error::other("invalid dedup snapshot"));
            }
        }
        self.image = image;
        Ok(())
    }
    fn freeze_bounded(&self, group: u64, max: usize) -> Result<Vec<u8>, CaptureError<io::Error>> {
        if group != self.image.group {
            return Err(CaptureError::Application(io::Error::other(
                "snapshot group mismatch",
            )));
        }
        struct Bounded {
            bytes: Vec<u8>,
            max: usize,
            exceeded: bool,
        }
        impl Write for Bounded {
            fn write(&mut self, bytes: &[u8]) -> io::Result<usize> {
                if bytes.len() > self.max.saturating_sub(self.bytes.len()) {
                    self.exceeded = true;
                    return Err(io::Error::other("snapshot size limit"));
                }
                self.bytes.extend_from_slice(bytes);
                Ok(bytes.len())
            }
            fn flush(&mut self) -> io::Result<()> {
                Ok(())
            }
        }
        let mut writer = Bounded {
            bytes: Vec::new(),
            max,
            exceeded: false,
        };
        if let Err(error) = serde_json::to_writer(&mut writer, &self.image) {
            return Err(if writer.exceeded {
                CaptureError::Refused(CaptureRefusal::SizeLimit)
            } else {
                CaptureError::Application(io::Error::other(error))
            });
        }
        Ok(writer.bytes)
    }
    fn disk_state(&mut self) -> Option<&mut dyn DiskState> {
        if self.disk.is_some() {
            Some(self)
        } else {
            None
        }
    }
}
impl DiskState for DemoFsm {
    fn durable_applied(&self) -> io::Result<Option<Vec<u8>>> {
        self.disk
            .as_ref()
            .ok_or_else(|| io::Error::other("not disk-backed"))?
            .db
            .applied_record()
    }
    fn apply_durable(
        &mut self,
        group: u64,
        index: u64,
        data: Option<&[u8]>,
        applied: &AppliedState,
    ) -> io::Result<ApplyOut> {
        if let Some(spec) = data.and_then(|data| data.strip_prefix(BLOB_PREFIX)) {
            let blob = generate_blob(spec)?;
            return self.apply_blob(index, &blob, applied);
        }
        let command = data.map(serde_json::from_slice::<Command>).transpose()?;
        if let Some(command) = &command {
            self.check_key(group, &command.key)?;
            self.gate.wait(&command.command_id)?;
        }
        let disk = self
            .disk
            .as_ref()
            .ok_or_else(|| io::Error::other("not disk-backed"))?;
        let mut batch = WriteBatch::default();
        let default = disk.db.cf("default")?;
        batch.put_cf(default, b"applied_index", index.to_be_bytes());
        let mut effects = Vec::new();
        if let Some(command) = command {
            let calls = DiskImage::read_u64(&disk.db, b"apply_calls")?.unwrap_or(0) + 1;
            batch.put_cf(default, b"apply_calls", calls.to_be_bytes());
            let existing = disk.command(&command.command_id)?;
            let (effect, new) = decide(existing.as_ref(), disk.value(&command.key)?, &command)?;
            if new {
                batch.put_cf(
                    disk.db.cf(VALUES)?,
                    &command.key,
                    serde_json::to_vec(&effect.value)?,
                );
                batch.put_cf(
                    disk.db.cf(COMMANDS)?,
                    &command.command_id,
                    serde_json::to_vec(&(&command, &effect))?,
                );
            }
            effects = serde_json::to_vec(&effect)?;
        }
        disk.db.commit(batch, applied)?;
        Ok(ApplyOut { effects })
    }
    fn snapshot_workspace(&self) -> io::Result<std::path::PathBuf> {
        self.disk_db()?.snapshot_workspace()
    }
    fn checkpoint(&self, dir: &std::path::Path) -> io::Result<()> {
        self.disk_db()?.checkpoint(dir)
    }
    fn inspect_checkpoint(&self, dir: &std::path::Path) -> io::Result<Option<Vec<u8>>> {
        self.disk_db()?.inspect_checkpoint(dir)
    }
    fn install_checkpoint(&mut self, dir: &std::path::Path) -> io::Result<()> {
        self.disk
            .as_mut()
            .ok_or_else(|| io::Error::other("not disk-backed"))?
            .db
            .install_checkpoint(dir)
    }
}
impl DemoFsm {
    fn disk_db(&self) -> io::Result<&DiskFsmDb> {
        Ok(&self
            .disk
            .as_ref()
            .ok_or_else(|| io::Error::other("not disk-backed"))?
            .db)
    }
    fn apply_blob(
        &mut self,
        index: u64,
        blob: &[u8],
        applied: &AppliedState,
    ) -> io::Result<ApplyOut> {
        let db = self.disk_db()?;
        let default = db.cf("default")?;
        let previous = db
            .db()
            .get_cf(default, b"blob_chain")
            .map_err(io::Error::other)?
            .unwrap_or_default();
        let mut chain = Sha256::new();
        chain.update(&previous);
        chain.update(index.to_be_bytes());
        chain.update(Sha256::digest(blob));
        let mut batch = WriteBatch::default();
        batch.put_cf(default, b"applied_index", index.to_be_bytes());
        batch.put_cf(default, b"blob_chain", chain.finalize());
        let count = DiskImage::read_u64(db, b"blob_count")?.unwrap_or(0) + 1;
        let bytes = DiskImage::read_u64(db, b"blob_bytes")?.unwrap_or(0) + blob.len() as u64;
        batch.put_cf(default, b"blob_count", count.to_be_bytes());
        batch.put_cf(default, b"blob_bytes", bytes.to_be_bytes());
        batch.put_cf(db.cf(BLOBS)?, index.to_be_bytes(), blob);
        db.commit(batch, applied)?;
        Ok(ApplyOut::default())
    }
}
impl SlotStateMachine for DemoFsm {
    fn query(&self, group: u64, request: &[u8]) -> io::Result<Vec<u8>> {
        let key: String = serde_json::from_slice(request)?;
        self.check_key(group, &key)?;
        if let Some(disk) = &self.disk {
            return Ok(serde_json::to_vec(&serde_json::json!({
                "key": key,
                "value": disk.value(&key)?,
                "apply_calls": DiskImage::read_u64(&disk.db, b"apply_calls")?.unwrap_or(0),
                "commands": disk.commands()?,
                "storage": "disk",
                "applied_index": DiskImage::read_u64(&disk.db, b"applied_index")?,
                "opened_index": disk.opened_index,
                "blobs": disk.blob_facts()?,
            }))?);
        }
        Ok(serde_json::to_vec(
            &serde_json::json!({"key":key,"value":self.image.values.get(&key).copied().unwrap_or(0),"apply_calls":self.image.apply_calls,"commands":self.image.commands}),
        )?)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use multiraft_slot::{
        contiguous_bucket_table, LayoutConfig, NodeAddress, RouteVersion, SlotAssignment, SlotId,
        BUCKET_COUNT, FORMAT_VERSION,
    };
    fn fsm() -> DemoFsm {
        let layout = ClusterLayout::new(LayoutConfig {
            cluster_id: "test".into(),
            format_version: FORMAT_VERSION,
            route_version: RouteVersion::Sha256Bucket256V1,
            bucket_count: BUCKET_COUNT,
            slot_count: 1,
            group_id_base: 100,
            nodes: vec![NodeAddress {
                node_id: 1,
                raft: "127.0.0.1:1".parse().unwrap(),
                application_rpc: "127.0.0.1:2".parse().unwrap(),
            }],
            buckets: contiguous_bucket_table(1).unwrap(),
            slots: vec![SlotAssignment {
                slot: SlotId(0),
                voters: vec![1],
                preferred_initializer: 1,
                soft_preferred_leader: 1,
            }],
        })
        .unwrap();
        DemoFsm {
            image: Image {
                group: 100,
                ..Image::default()
            },
            layout,
            gate: Arc::new(Gate::default()),
            disk: None,
        }
    }
    #[test]
    fn duplicate_intent_snapshot_and_identity() {
        let mut state = fsm();
        let mut command = Command {
            key: "a".into(),
            command_id: "id".into(),
            delta: 3,
        };
        let bytes = serde_json::to_vec(&command).unwrap();
        let first = state.apply(100, 1, &bytes).unwrap();
        assert_eq!(state.apply(100, 2, &bytes).unwrap().effects, first.effects);
        command.delta = 9;
        let rejection: Effect = serde_json::from_slice(
            &state
                .apply(100, 3, &serde_json::to_vec(&command).unwrap())
                .unwrap()
                .effects,
        )
        .unwrap();
        assert!(!rejection.accepted);
        assert_eq!(state.image.values["a"], 3);
        let snapshot = state.snapshot(100).unwrap();
        let mut recovered = fsm();
        recovered.restore(100, &snapshot).unwrap();
        assert_eq!(
            recovered.apply(100, 4, &bytes).unwrap().effects,
            first.effects
        );
        assert!(recovered.restore(101, &snapshot).is_err());
        assert!(recovered.apply(101, 5, &bytes).is_err());
        assert!(matches!(
            recovered.freeze_bounded(100, 1),
            Err(CaptureError::Refused(CaptureRefusal::SizeLimit))
        ));
    }
}
